-- ============================================================================
--  一次性初始化：创建数据库
-- ----------------------------------------------------------------------------
--  ⚠️ 本脚本只在**首次部署**时手动执行一次，不参与 Flyway 迁移。
--
--  为什么单独拆出来：
--    Flyway 迁移脚本运行时已经连接在目标库上，里面不能有 CREATE DATABASE / USE。
--    建库属于「部署前动作」，与「表结构演进」是两件事，混在一起会让迁移脚本
--    在已有库的环境下无法复用。
--
--  执行方式：
--    mysql -u root -p < schema/00_create_database.sql
-- ============================================================================

CREATE DATABASE IF NOT EXISTS `bot`
    DEFAULT CHARACTER SET utf8mb4
    COLLATE utf8mb4_0900_ai_ci;

