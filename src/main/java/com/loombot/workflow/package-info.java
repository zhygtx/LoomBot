/**
 * 工作流模块 —— DAG 定义、调度执行与执行记录。
 *
 * <h2>职责</h2>
 *
 * <ul>
 *   <li>工作流定义：节点（{@code WorkflowNode}）、边（{@code WorkflowEdge}）、画布视图
 *   <li>执行引擎：按 DAG 拓扑调度、条件分支、参数传递与类型转换
 *   <li>触发器：定时、事件、手动
 *   <li>执行记录：每次运行的节点级追踪（耗时、输入输出、异常）
 *   <li>大文本离线存储（执行日志可能极大，不宜直接塞进主表）
 * </ul>
 *
 * <h2>为什么单独成模块</h2>
 *
 * <p>工作流引擎与机器人平台<b>没有本质耦合</b> —— 它只是「按图执行一串可调用对象」。 单独成模块既便于测试，也让它未来可以被独立复用或抽成服务。
 *
 * <h2>表归属</h2>
 *
 * <p>{@code workflow_info} / {@code workflow_execution} / {@code big_text} 等（脚本待补）。
 *
 * <h2>边界规则</h2>
 *
 * <p>只允许依赖 {@code common}。节点需要调用插件能力时，通过 {@code plugin} 模块的接口， 不要直接引用插件实体 ——
 * 否则工作流引擎会被插件实现绑死，失去复用价值。
 */
