-- ============================================================================
--  V5 · 给 sys_user.email 加唯一索引（它是登录凭据，必须唯一）
-- ----------------------------------------------------------------------------
--  为什么必须补这一条：
--
--  ★ email 是登录凭据，而 V1 只给它建了普通索引 idx_email
--      登录链路是「按邮箱找唯一一行 → 校验密码」，用的是 MyBatis-Plus 的
--      selectOne。一旦同一个邮箱存在两行，selectOne 会直接抛
--      TooManyResultsException —— 表现是登录接口 500，而且**只有这个邮箱**登录会 500，
--      别的邮箱一切正常。这类「数据决定的偶发故障」是最难查的一类。
--
--  ★ 原来靠应用层查重是不够的
--      UserService.register 会先查一次「邮箱是否已存在」，两个请求同时通过检查时，
--      唯一索引是最后一道防线。没有索引就没有这道防线 —— 而并发注册同一个邮箱
--      在「点两次提交」「刷新重发」下并不罕见，不需要攻击者也能撞上。
--
--  ★ 为什么可以安全地加
--      email 列可空，而 MySQL 的唯一索引允许**多个 NULL 共存**（这条特性在
--      sys_permission.uk_perm 上已经实测确认过，见 docs/database.md）。所以
--      「将来可能出现的无邮箱用户」不会因为这条索引而互相冲突。
--      执行本迁移前已确认 bot.sys_user 为空表（0 行），不存在需要先去重的历史数据。
--
--  ★ 为什么顺手删掉 idx_email
--      uk_email 是 (email) 上的索引，等值查询的访问路径与 idx_email 完全重合。
--      留着它只会多占一份空间、多一次写入维护，没有任何查询会用到它。
--
--  ⚠️ 应用层仍然保留「先查一次给出友好提示」的逻辑：索引负责正确性，
--      查重负责给用户一句能看懂的话（而不是 500 或「系统内部错误」）。
-- ============================================================================

ALTER TABLE `sys_user`
    ADD UNIQUE KEY `uk_email` (`email`);

ALTER TABLE `sys_user`
    DROP INDEX `idx_email`;
