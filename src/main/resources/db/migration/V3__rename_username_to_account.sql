-- ============================================================================
--  V3 · sys_user.username → sys_user.account
-- ----------------------------------------------------------------------------
--  为什么改名（这是本次变更的全部理由，不是排版偏好）：
--
--  ★ 「登录名」这个叫法在新方案下是错的，且会主动误导人
--      登录与找回密码都走**邮箱 + 密码**（见 docs/auth.md）。于是 username
--      里存的这串东西**不再用于登录**，把它注释成「登录名」会让人以为
--      「登录时该填它」，而这恰好是错的 —— 一个名字把使用者引向相反的行为。
--
--  ★ 项目没有用户之间的交流，不存在「展示名」这一层语义
--      没有社区、没有好友、没有 @ 提及，所以「用户名」这个中文词本来会
--      暗示「别人看到的名字」。它既不是展示名，也不用于登录，那它只能是
--      **账号**：一个稳定的、唯一的、用于标识这一行数据归属的编号式标识。
--
--  ★ 前端从一开始就叫它 account
--      登录/注册/找回密码三个页面提交的字段名都是 account。改列名之后
--      DB 列 / 后端 DTO / 前端字段三处同名，不再需要任何心智翻译。
--
--  配套变更（同一批）：docs/database.md、docs/auth.md、ErrorCode、
--  auth 模块的实体与 DTO、前端三个页面上的「用户名」字样。
--
--  ⚠️ 为什么是 ALTER 而不是直接改 V1
--      V1 已经执行过（bot 库的 flyway_schema_history 里有记录），
--      Flyway 会校验 checksum —— 改 V1 会让应用**启动直接失败**。
--      规则见 docs/database.md：变更表结构一律新增 V{n}，不改历史脚本。
-- ============================================================================

ALTER TABLE `sys_user`
    CHANGE COLUMN `username` `account` VARCHAR(64) NOT NULL COMMENT '账号（唯一标识，不用于登录；登录走邮箱）';

-- 唯一索引跟着改名。不改也能跑，但 uk_username 指着 account 列是典型的
-- 「名字与内容不符」，下一次有人读到它就得重新确认一遍。
ALTER TABLE `sys_user`
    RENAME INDEX `uk_username` TO `uk_account`;
